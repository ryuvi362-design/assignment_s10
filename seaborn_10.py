import seaborn as sns
import matplotlib.pyplot as plt
import pandas as pd

# Sample Spotify data
days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']
songs = [25, 30, 22, 35, 40, 55, 48]

df = pd.DataFrame({
    'Day': days,
    'Songs Streamed': songs
})

# Apply poster context
sns.set(context='poster')

# Create barplot
sns.barplot(data=df, x='Day', y='Songs Streamed')

plt.title('Spotify Daily Songs Streamed')
plt.xlabel('Day')
plt.ylabel('Number of Songs')
plt.show()

cuisines = [
    'Indian', 'Chinese', 'Italian', 'Indian', 'Indian',
    'Chinese', 'Italian', 'Indian', 'Chinese', 'Italian',
    'Indian', 'Chinese', 'Indian', 'Italian', 'Chinese'
]

df = pd.DataFrame({'Cuisine': cuisines})

sns.countplot(data=df, x='Cuisine', palette='colorblind', hue='Cuisine', legend=False)

plt.title('Zomato Orders by Cuisine')
plt.xlabel('Cuisine Type')
plt.ylabel('Number of Orders')
plt.show()

days = list(range(1, 15))
steps = [
    4500, 5200, 6000, 4800, 7000, 8500, 7500,
    6200, 9000, 7800, 8200, 9500, 8800, 10000
]

df = pd.DataFrame({
    'Day': days,
    'Steps': steps
})

sns.set(context='notebook', palette='muted')

sns.lineplot(data=df, x='Day', y='Steps', marker='o')

plt.title('Daily Step Counts - 14 Days')
plt.xlabel('Day')
plt.ylabel('Number of Steps')
plt.xticks(days)
plt.show()

df = pd.DataFrame({
    'Platform': ['Spotify', 'YouTube', 'Instagram', 'Netflix'],
    'Users': [500, 700, 600, 400]
})

sns.set(context='talk', palette='deep')

plt.figure(figsize=(8, 4))
sns.barplot(data=df, x='Platform', y='Users', hue='Platform', palette='deep', legend=False)
plt.title('Default Styling: Deep + Talk')
plt.show()

sns.set(context='poster', palette='colorblind')

plt.figure(figsize=(8, 4))
sns.barplot(data=df, x='Platform', y='Users', hue='Platform', palette='colorblind', legend=False)
plt.title('Updated Styling: Colorblind + Poster')
plt.show()

df = pd.DataFrame({
    'Category': [
        'Mobiles',
        'Laptops',
        'Clothing',
        'Home Appliances',
        'Books'
    ],
    'Sales': [150000, 120000, 90000, 110000, 45000]
})
sns.set(
    context='talk',
    palette='deep',
    font_scale=1.1,
    style='whitegrid'
)
plt.figure(figsize=(11, 6))

sns.barplot(
    data=df,
    x='Category',
    y='Sales',
    hue='Category',
    palette='deep',
    legend=False
)

plt.title('Flipkart Sales Dashboard', pad=20)
plt.xlabel('Product Category')
plt.ylabel('Total Sales (Rs)')
plt.xticks(rotation=20)
plt.tight_layout()
plt.show()